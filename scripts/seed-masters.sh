#!/usr/bin/env bash
#
# 選択肢マスタに初期データを入れる。
#
# 画面（frontend/src/mock/masters.ts）と同じ値を入れている。モックと実データがずれると、
# S-2 のプルダウンで選んだ氏名をサーバーが「存在しない」と判定して解除できなくなる。
#
# **同じキー（category + code）への put-item は上書きになる。**
# 何度実行してもよい代わりに、S-6（マスタ管理・F-10）から直した内容も黙って戻る。
# 条件付き書き込みで既存を避ける案は採らない — シードをやり直したいときに効かなくなるため。
# 代わりに実行前に何を書くかを見せて確認を取る。
#
# マスタの CRUD は F-10（8/11 予定）で画面から行えるようにする。それまでの投入手段。
#
#   使い方:  ./scripts/seed-masters.sh
#
set -euo pipefail

TABLE="${MASTERS_TABLE:-q-documents-masters}"
REGISTERED_AT="2026-01-10"

export AWS_PAGER=""

# put <項目種別> <コード> <表示名> <状態> [追加属性のJSON断片]
#
# 追加属性は文書種類の numberingRule と製品コードの isCommon だけ。
# マスタ4種別を1つのテーブルで扱っているため、種別ごとに持つ属性が違う
# （shared/types.ts の MasterRecord が optional にしているのと同じ理由）。
put() {
  local category="$1" code="$2" name="$3" status="$4" extra="${5:-}"
  aws dynamodb put-item \
    --table-name "$TABLE" \
    --item "{
      \"category\":     {\"S\": \"${category}\"},
      \"code\":         {\"S\": \"${code}\"},
      \"name\":         {\"S\": \"${name}\"},
      \"status\":       {\"S\": \"${status}\"},
      \"registeredAt\": {\"S\": \"${REGISTERED_AT}\"}${extra}
    }" >/dev/null
  echo "  ${category} / ${code} / ${name} / ${status}"
}

cat <<'EOS'
選択肢マスタに以下を投入します（13件）。

  文書種類   / Q001   / PFMEA        / 有効 / 製品単位
  文書種類   / Q005   / QC工程表      / 有効 / 製品単位
  文書種類   / Q010   / 作業指示書    / 有効 / 工程単位

  製品コード / P-0001 / 製品A        / 有効
  製品コード / P-0002 / 製品B        / 有効
  製品コード / P-0003 / 製品C        / 無効   ← 廃番。S-1 の検索には（無効）付きで出る
  製品コード / P-0004 / 製品D        / 有効   ← 文書が1件も無い製品
  製品コード / COM001 / 共通作業      / 有効   ← 共通コード（作業指示書だけが紐づく）

  工程番号   / K001   / 工程1        / 有効
  工程番号   / K002   / 工程2        / 有効

  担当者     / E001   / 山田太郎      / 有効
  担当者     / E002   / 佐藤花子      / 有効
  担当者     / E003   / 鈴木一郎      / 無効   ← S-4 の「担当者を選び直す」経路の確認用

*** 注意 ***
同じ category + code のレコードは**上書き**されます。
S-6（マスタ管理）から氏名や状態を変更していた場合、その変更は失われます。
EOS

echo
read -r -p "テーブル ${TABLE} に上書きして投入しますか? [y/N] " answer
if [ "${answer}" != "y" ] && [ "${answer}" != "Y" ]; then
  echo "中止した"
  exit 0
fi

echo "==> 投入"

# 文書種類。numberingRule が文書番号の形と工程情報の要否を同時に決める（shared/types.ts）。
# 作業指示書も文書種類コードを持つ（番号には現れないが F-05 の絞り込みに要る）
put "文書種類" "Q001" "PFMEA"     "有効" ',"numberingRule": {"S": "製品単位"}'
put "文書種類" "Q005" "QC工程表"   "有効" ',"numberingRule": {"S": "製品単位"}'
put "文書種類" "Q010" "作業指示書" "有効" ',"numberingRule": {"S": "工程単位"}'

# 製品コード。P-0003 を無効にしてあるのは、無効化されたマスタが
# S-3（登録）では選べず S-1（検索）では（無効）付きで出ることを確認するため。
# COM001 は製品によらない共通作業。判定は isCommon で行い、コードの形式では判定しない
put "製品コード" "P-0001" "製品A"    "有効"
put "製品コード" "P-0002" "製品B"    "有効"
put "製品コード" "P-0003" "製品C"    "無効"
put "製品コード" "P-0004" "製品D"    "有効"
put "製品コード" "COM001" "共通作業"  "有効" ',"isCommon": {"BOOL": true}'

# 工程番号。工程名は工程番号と1対1で、対で選ばせない（採番時もマスタから引く）
put "工程番号" "K001" "工程1" "有効"
put "工程番号" "K002" "工程2" "有効"

# 担当者。登録するのは生産技術の担当者のみ（docs/DynamoDBテーブル設計.md）。
# 合言葉の解除（F-18）と、文書の担当者の照合に使う。
#
# E003 を無効で入れてあるのは、S-4 の「現行の担当者が無効化されていたら
# 既定値を置かず選び直させる」経路を実機で確認するため（docs/screens.md S-4）。
# 有効な担当者しかいないと、この分岐は一度も実行されないまま本番に出る
put "担当者" "E001" "山田太郎" "有効"
put "担当者" "E002" "佐藤花子" "有効"
put "担当者" "E003" "鈴木一郎" "無効"

echo "完了"
