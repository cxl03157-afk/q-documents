/**
 * 型の単一の正（CLAUDE.md §7）。
 * backend / frontend の両方から相対パスで読む。片側だけで型を再定義しない。
 *
 * ここに置くのは「両側が参照するもの」だけとする。
 * 画面だけが使う型（絞り込み条件など）は frontend/src/ に置く。
 */

// ---------------------------------------------------------------------------
// 文書台帳
// ---------------------------------------------------------------------------

/**
 * 文書の状態（CLAUDE.md §5）。
 *
 * 5値で固定なので union にする。string にすると打ち間違いがコンパイルを通ってしまい、
 * 「状態を書き換えられるのは非同期Lambdaだけ」という規律をコンパイラが助けてくれない。
 * 日本語リテラルなのは、この文字列がそのまま DynamoDB に入り画面にも出るため（変換層を挟まない）。
 */
export type DocumentStatus =
  | 'ファイル未登録'
  | '一部登録'
  | '最新'
  | '旧版'
  | '削除済み';

/**
 * 採番ルール。文書種類マスタが持ち、文書番号の形と工程情報の要否を同時に決める。
 *
 * - 製品単位: `文書種類_製品コード_Rev`      → 文書種類コードを番号に含める。工程情報は不要
 * - 工程単位: `製品コード_工程番号_工程名_Rev` → 文書種類コードは番号に含めない。工程情報が必須
 *
 * 作業指示書も文書種類コードを持つ（番号には現れないが、レコードの documentType と
 * F-05 の絞り込みに必要なため）。
 */
export type NumberingRule = '製品単位' | '工程単位';

/**
 * 文書台帳のレコード（DynamoDB: PK = 製品コード / SK = 文書ID#リビジョン）。
 *
 * 注意: DynamoDB から読んだ値に `as DocumentRecord` を付けても、実際の中身は検証されない。
 * 外から来た値は境界で検証してからこの型を名乗らせること（週2〜3で実装）。
 */
export type DocumentRecord = {
  /** PK。全文書が製品コードを持つのでパーティションキーにしている */
  productCode: string;

  /**
   * SK。`文書ID#リビジョン`（例: `Q001_P-0001#01`）。
   * documentNo から導出できるが、キーそのものなので保持する。
   * 毎回パースし直す方が事故のもと。
   */
  sortKey: string;

  /** 文書番号。ファイル名の正でもある（ファイル名 = 文書番号 + 拡張子） */
  documentNo: string;

  /**
   * 文書種類コード（例: `Q001`）。
   * union にしない。S-6 のマスタ管理で追加できる値なので、union にすると
   * 追加のたびに型を直すことになり、マスタで管理する意味が消える。
   * DocumentStatus が union なのは 5値が固定で遷移規律があるからで、扱いが違う理由はここ。
   */
  documentType: string;

  /** 工程番号。採番ルールが「工程単位」のときのみ存在する */
  processNo?: string;

  /** 工程名。同上。`#` と `/` は含められない（SK と S3キーが壊れるため。CLAUDE.md §4） */
  processName?: string;

  /**
   * リビジョン。`'01'` 形式の2桁ゼロ埋め。
   * number にすると `1` になり SK 組み立てのたびにゼロ埋めが要る。文字列で持つ。
   * 2桁であることの保証は採番の純粋関数側で行う（型では表現できない）。
   */
  revision: string;

  /** 担当者。生産技術の担当者のみ（担当者マスタの登録対象がそれだけ） */
  owner: string;

  /** 文書発行日。S-3 で人が入力する日付 */
  issuedAt: string;

  /** DBへの登録日時。システムが打つ。issuedAt とは別物なので分けている */
  registeredAt: string;

  status: DocumentStatus;

  /**
   * S3キー。両方 undefined なら「ファイル未登録」、片方だけなら「一部登録」、
   * 両方揃うと非同期Lambdaが「最新」にする。
   * この optional 性が状態5値と対応している。
   *
   * TODO(週3): 状態遷移の実装時に status を判別子にした union へ格上げする。
   * 今やっても DynamoDB の境界で `as` を通すと守られないので、境界検証と対で入れる。
   */
  s3KeyPdf?: string;
  s3KeyExcel?: string;
};

/**
 * S-7 で編集できる項目（screens.md S-7）。
 *
 * 文書番号を構成する項目は変更できない（変えれば文書番号も SK も変わるため）。
 * 状態も編集できない（手で変えられると、ファイルが無いのに「最新」になり
 * F-04 のアーカイブ判定が狂う）。
 * Pick で絞ることで、status を受け取る口が型として存在しなくなる。
 */
export type DocumentPatch = Pick<DocumentRecord, 'owner' | 'issuedAt'>;

// ---------------------------------------------------------------------------
// 選択肢マスタ
// ---------------------------------------------------------------------------

/** マスタの項目種別（DynamoDB マスタテーブルの PK） */
export type MasterCategory = '文書種類' | '製品コード' | '工程番号' | '担当者';

/** 物理削除はしない（過去の文書が参照しているため）。無効にするだけ */
export type MasterStatus = '有効' | '無効';

/**
 * 選択肢マスタのレコード（DynamoDB: PK = 項目種別 / SK = コード番号）。
 *
 * 種別ごとに型を分けない。テーブルが1本なので、型を4つに分けると
 * GET /masters のレスポンスを扱うたびに分岐が必要になる。
 * どの種別も「コードと表示名の組」なので name 1本で足りる。
 */
export type MasterRecord = {
  /** PK */
  category: MasterCategory;

  /** SK。例: 文書種類なら `Q001`、工程番号なら `K001`、製品コードなら `P-0001` */
  code: string;

  /** 表示名。文書種類なら `PFMEA`、工程番号なら `工程1`、担当者なら氏名 */
  name: string;

  status: MasterStatus;

  registeredAt: string;

  /**
   * category === '文書種類' のときのみ持つ。
   * マスタ4種別を1つの型で扱っているため optional になる。
   */
  numberingRule?: NumberingRule;

  /**
   * category === '製品コード' のときのみ持つ。
   *
   * 製品によらない共通の作業がある。これは製品コードの代わりに `COM001` のような
   * 記号を割り当てて扱う。共通コードに紐づくのは工程単位の文書（作業指示書）だけで、
   * 製品単位の文書（PFMEA・QC工程表）は存在しない。
   *
   * 真偽値で持つのは、キーの形式（`P-` で始まる等）で判定させないため。
   * 命名規則で判定すると、記号の付け方を変えた瞬間に壊れる。
   */
  isCommon?: boolean;
};

/**
 * `PATCH /masters/{id}` で更新できる項目（docs/screens.md S-6）。
 *
 * category・code は変更できない（変えれば別のレコードになるため。パスの `id` が正）。
 * status を含むのは、無効化/有効化も同じエンドポイントで行うため
 * （`DELETE /masters` は無い。物理削除はしない）。
 * 全項目 optional なのは、無効化のときは status だけ、名称修正のときは name だけを
 * 送れば足りるようにするため。少なくとも1項目は必須で、ハンドラ側で検証する。
 */
export type MasterPatch = Partial<Pick<MasterRecord, 'name' | 'status' | 'numberingRule' | 'isCommon'>>;
